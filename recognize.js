/* ============================================================
   Распознавание операций выписки по статьям P&L
   ------------------------------------------------------------
   1. Если операция пришла из карточки счёта 51 (1С), сначала смотрим
      корреспондирующий счёт и статью ДДС: это самый надёжный признак.
   2. Потом словарь признаков: назначение платежа (высокая уверенность),
      название контрагента (средняя). Общие признаки (low:true) проверяются
      последними и дают низкую уверенность.
   Чтобы научить сайт новому признаку, добавь строку в RECOGNITION_RULES.
   ============================================================ */
(function (root) {
  const UNC_IN = 'Поступления без категории';
  const UNC_OUT = 'Расходы без категории';
  const MOVE = 'Переводы между своими счетами';
  const LOAN = 'Кредиты и займы';
  const CAPEX = 'Покупка оборудования';

  // sign: '+' поступление, '-' списание, '*' любое
  // s: подстатья (строка) или функция (текст, поступление?) => подстатья
  const R = (id, re, c, sign, s, low) => ({ id, re, c, sign, s, low: !!low });

  const RECOGNITION_RULES = [
    // ---------- Поступления ----------
    R('acq', /эквайринг/, 'Выручка B2C (Подписки)', '+'),
    R('saas', /saas|доступ\S* к (сайту|платформ|сервис)|подписк/, 'Выручка B2B (Доступ к сайту)', '+'),
    R('mp', /wildberries|вайлдберриз|(?<![а-я])рвб(?![а-я])|ozon|озон|интернет решения|яндекс маркет|маркетплейс/, 'Выручка: маркетплейсы', '+'),
    R('int', /процент\S* (на|по) остат|начислен\S* процент|капитализац/, 'Доход: проценты банка', '+', 'Проценты на остаток'),
    R('rev', /оплат\S* (по|за|услуг|товар|счет|сч\.|договор)|по счету|по договору|реализац|выручк/, 'Выручка (прочая)', '+', null, true),

    // ---------- Движения вне прибыли ----------
    R('move', /перевод собственных|собственных средств|между своими счетами|внутреннее перемещение|перемещение денежных/, MOVE, '*'),
    R('loanpct', /уплат\S* процент|процент\S* (по|за) (кредит|займ)/, 'Проценты по кредитам', '-', 'Проценты'),
    R('loan', /кредит|займ/, LOAN, '*', (t, inc) => inc ? 'Получение' : 'Погашение'),

    // ---------- Распределение прибыли и налог на прибыль ----------
    R('div', /дивиденд/, 'Дивиденды', '-'),
    R('ptax', /налог\S* на прибыль/, 'Налог на прибыль', '-'),

    // ---------- Возвраты покупателям ----------
    R('refund', /возврат\S* (излишне|ошибочно|аванса|оплаты|денежных средств)/, 'Возвраты клиентам', '-'),

    // ---------- Налоги и взносы ----------
    R('tax', /единый налогов|(?<![а-я])енп(?![а-я])|ндфл|страхов\S* взнос|взнос\S* (на|в)|(?<!без )налог|уфк|ифнс|(?<![а-я])фнс(?![а-я])|казначейств/, 'Налоги и взносы', '-',
      t => /енп|единый налогов/.test(t) ? 'ЕНП' : /ндфл/.test(t) ? 'НДФЛ' : /взнос/.test(t) ? 'Страховые взносы' : 'Налоги'),

    // ---------- Подрядчики (до зарплаты и IT: «реестр самозанятых», «разработка ПО») ----------
    R('ctr', /возмездного оказания|разработк|подряд|самозанят|(?<![а-я])гпх(?![а-я])/, 'Подрядчики (Услуги)', '-',
      t => /разработк/.test(t) ? 'Разработка ПО' : /дизайн/.test(t) ? 'Дизайн' : 'Услуги подрядчиков'),

    // ---------- Персонал ----------
    R('pay', /заработн|зарплат|аванс\S* по (заработ|зп)|реестр|отпускн|больничн|преми[ия]/, 'Зарплата (ФОТ)', '-', 'Зарплата'),

    // ---------- Аренда, лизинг, оборудование ----------
    R('rent', /аренд/, 'Аренда', '-', t => /склад/.test(t) ? 'Аренда склада' : 'Аренда офиса'),
    R('lease', /лизинг/, 'Лизинг', '-', 'Лизинговые платежи'),
    R('capex', /основн\S* средств|ноутбук|компьютерн\S* техник|оборудовани/, CAPEX, '-', t => capexSub(t)),

    // ---------- Маркетинг ----------
    R('mkt', /реклам|продвижен|маркетинг|директ|vk ads|таргет|\bseo\b|\bsmm\b|контекст|\bpr\b/, 'Маркетинг и реклама', '-'),

    // ---------- IT ----------
    R('it', /вычислительн|облак|облачн|хостинг|сервер|домен|лиценз|программн\S* обеспеч|(?<![а-я0-9])1с(?![а-я])|интернет|связ[ьи]|телефон/, 'IT инфраструктура', '-',
      t => /облак|облачн/.test(t) ? 'Облачные сервисы' : /домен/.test(t) ? 'Домены' : /сервер|хостинг/.test(t) ? 'Серверы' :
        /лиценз|программн|(?<![а-я0-9])1с(?![а-я])/.test(t) ? 'Лицензии' : /интернет|связ|телефон/.test(t) ? 'Связь и интернет' : ''),

    // ---------- Офис и хозяйство ----------
    R('ofc', /хозяйствен|хозтовар|канцтовар|канцеляр|вода|клининг|уборк|офисн\S* (товар|мебел|расход)/, 'Офисные и хоз. расходы', '-',
      t => /канц/.test(t) ? 'Канцтовары' : /вода/.test(t) ? 'Вода' : /клининг|уборк/.test(t) ? 'Клининг' : ''),

    // ---------- Банк ----------
    R('bank', /комисси|расчетно-кассов|(?<![а-я])рко(?![а-я])|обслуживан\S* (счет|сч\.)|за ведение счет|услуги банк/, 'Услуги банка', '-', 'РКО и комиссии'),

    // ---------- Общие признаки для чужих выписок ----------
    R('trip', /такси|топлив|бензин|(?<![а-я])азс(?![а-я])|командир|авиабилет|(?<![а-я])ржд(?![а-я])|гостиниц|проживан/, 'Командировки и транспорт', '-', null, true),
    R('prof', /бухгалтер|юридическ|консультац|аудит|нотари/, 'Профессиональные услуги', '-', null, true),
    R('log', /доставк|курьер|почт|сдэк|логистик|перевозк/, 'Логистика и доставка', '-', null, true),
    R('buy', /товар|поставк|закупк|материал|сырь|продукт/, 'Закупки', '-', null, true),
  ];

  // подстатья покупки: что именно купили
  function capexSub(t) {
    return /ноутбук|компьютер|моноблок|монитор|макбук|macbook/.test(t) ? 'Ноутбуки и компьютеры' : /сервер|схд|коммутатор|маршрутизатор/.test(t) ? 'Серверы и сетевое оборудование' :
      /мебел|стол|кресл|стул/.test(t) ? 'Мебель' : /автомоб|транспорт/.test(t) ? 'Транспорт' : 'Оборудование';
  }
  const norm = s => String(s || '').toLowerCase().replace(/ё/g, 'е');
  const paren = n => { const m = String(n || '').match(/\(([^)]+)\)\s*$/); return m ? m[1].trim() : ''; };
  const cap = s => s ? s[0].toUpperCase() + s.slice(1) : s;

  /* Слой 1С: корреспондирующий счёт и статья ДДС.
     Возвращает готовый результат, или {hint:'rev'} (выручка, уточнить словарём), или null. */
  function byAccount(acc, dds, inc, text) {
    const a = String(acc || '').trim(), t = norm(dds);
    if (!a && !t) return null;
    const w = (a ? 'счёт ' + a : '') + (a && dds ? ' · ' : '') + (dds || '');
    const res = (c, v, k) => ({ c, v: v || '', k: k || 'acc', w, q: 'h' });
    const is = re => re.test(a);
    if (is(/^(50|51|52|55)(\.|$)/) || is(/^57\.0[12]/) || /перемещ|перевод.*собствен/.test(t)) return res(MOVE, inc ? 'Поступление' : 'Списание', 'move');
    if (is(/^0[178](\.|$)/) || /основн\S* средств|внеоборот|нематериальн/.test(t)) return res(CAPEX, capexSub(text || ''), 'capex');
    if (is(/^6[67](\.|$)/) || /кредит|займ/.test(t)) {
      if (is(/^6[67]\.0[24]$/) || /процент/.test(t)) return res('Проценты по кредитам', 'Проценты', 'loanpct');
      return res(LOAN, inc ? 'Получение' : 'Погашение', 'loan');
    }
    if (!inc && (is(/^70(\.|$)/) || /оплата труда|заработн/.test(t))) return res('Зарплата (ФОТ)', 'Зарплата', 'pay');
    if (!inc && is(/^68\.04/)) return res('Налог на прибыль', '', 'ptax');
    if (!inc && (is(/^6[89](\.|$)/) || /налог|взнос/.test(t)))
      return res('Налоги и взносы', is(/^68\.90/) ? 'ЕНП' : is(/^68\.01/) ? 'НДФЛ' : is(/^69/) ? 'Страховые взносы' : 'Налоги', 'tax');
    if (!inc && (is(/^75\.02/) || /дивиденд/.test(t))) return res('Дивиденды', '', 'div');
    if (is(/^62(\.|$)/) || /покупател/.test(t)) return inc ? { hint: 'rev', w } : res('Возвраты клиентам', '', 'refund');
    if (inc && (is(/^57\.03/) || is(/^76/))) return { hint: 'rev', w };
    return null;
  }

  /* Словарь: сначала точные признаки (назначение, затем контрагент), потом общие */
  function byWords(name, purpose, inc) {
    const p = norm(purpose), n = norm(name), both = p + ' ' + n;
    for (const low of [false, true])
      for (const [txt, q, raw] of [[p, 'h', purpose], [n, 'm', name]]) {
        if (!txt) continue;
        for (const r of RECOGNITION_RULES) {
          if (r.low !== low || (r.sign !== '*' && (r.sign === '+') !== inc)) continue;
          const m = txt.match(r.re);
          if (!m) continue;
          let v = typeof r.s === 'function' ? r.s(both, inc) : (r.s || '');
          if (!v && !inc) v = cap(paren(name));
          // признак расширяем до целых слов: «реклам» → «рекламных»
          const s = String(raw), L = /[а-яёa-z0-9-]/i;
          let a = m.index, b = m.index + m[0].length;
          while (a > 0 && L.test(s[a - 1])) a--;
          while (b < s.length && L.test(s[b])) b++;
          return { c: r.c, v, k: r.id, w: s.slice(a, b), q: low ? 'l' : q };
        }
      }
    return null;
  }

  /* Возвращает {c, v, k, w, q}:
     c статья, v подстатья (может быть ''), k id правила, w найденный признак,
     q уверенность: 'h' высокая, 'm' средняя, 'l' низкая, '' не распознано.
     ex = {acc, dds}: корреспондирующий счёт и статья ДДС из карточки 1С */
  function classify(name, purpose, amount, ex) {
    const inc = amount > 0, A = ex ? byAccount(ex.acc, ex.dds, inc, norm(purpose) + ' ' + norm(name)) : null;
    if (A && !A.hint) return A;
    const W = byWords(name, purpose, inc);
    if (A && A.hint === 'rev') {
      if (W && W.q !== 'l' && /^(выручка|доход)/i.test(W.c)) return W;
      return { c: 'Выручка (прочая)', v: '', k: 'acc', w: A.w, q: 'h' };
    }
    return W || { c: inc ? UNC_IN : UNC_OUT, v: '', k: '', w: '', q: '' };
  }

  const api = { classify, RECOGNITION_RULES, UNC_IN, UNC_OUT, MOVE, LOAN, CAPEX };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.Recognizer = api;
})(typeof window !== 'undefined' ? window : globalThis);
